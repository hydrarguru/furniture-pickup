#!/usr/bin/env bash
# Local Garage (S3) for development, run natively (macOS: `brew install garage`).
#   ./scripts/garage-dev.sh start   # run the server in the foreground (Ctrl+C to stop)
#   ./scripts/garage-dev.sh init    # one-time setup while the server runs; safe to re-run
# Used by scripts/dev.sh:
#   serve               start, or keep an already running Garage on :3900
#   wait                block until the S3 port answers
#   init --if-needed    run init only when the bucket or the API key is missing
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DIR="$ROOT/.garage-dev"
CONFIG="$DIR/garage.toml"
API_ENV="$ROOT/apps/api/.env"
BUCKET="pickup-images"
KEY_NAME="pickup-api-dev"
APP_ORIGIN="${APP_ORIGIN:-http://localhost:5173}"

command -v garage >/dev/null || { echo "garage not found. Install it with: brew install garage" >&2; exit 1; }

write_config() {
  [[ -f "$CONFIG" ]] && return
  mkdir -p "$DIR/meta" "$DIR/data"
  cat >"$CONFIG" <<TOML
# Generated by scripts/garage-dev.sh for local development only.
metadata_dir = "$DIR/meta"
data_dir = "$DIR/data"
db_engine = "sqlite"
replication_factor = 1

rpc_bind_addr = "127.0.0.1:3901"
rpc_public_addr = "127.0.0.1:3901"
rpc_secret = "$(openssl rand -hex 32)"

[s3_api]
s3_region = "garage"
api_bind_addr = "127.0.0.1:3900"
TOML
  echo "Wrote $CONFIG"
}

g() { garage -c "$CONFIG" "$@"; }

# Set KEY=VALUE in apps/api/.env, replacing an existing (or commented-out) line.
set_env() {
  local key="$1" value="$2"
  if grep -qE "^#? ?$key=" "$API_ENV"; then
    sed -i.bak -E "s|^#? ?$key=.*|$key=$value|" "$API_ENV" && rm -f "$API_ENV.bak"
  else
    echo "$key=$value" >>"$API_ENV"
  fi
}

init() {
  write_config
  g status >/dev/null 2>&1 || { echo "Garage is not running. Start it first: pnpm storage:dev" >&2; exit 1; }

  if g layout show 2>/dev/null | grep -q "No nodes currently have a role"; then
    g layout assign -z dev -c 5G "$(g node id -q | cut -d@ -f1)"
    g layout apply --version 1
  fi

  g bucket info "$BUCKET" >/dev/null 2>&1 || g bucket create "$BUCKET"

  [[ -f "$API_ENV" ]] || cp "$ROOT/apps/api/.env.example" "$API_ENV"
  if ! g key info "$KEY_NAME" >/dev/null 2>&1; then
    # Import a key we generate, so its secret can be written to .env without scraping CLI output.
    local id="GK$(openssl rand -hex 12)" secret
    secret="$(openssl rand -hex 32)"
    g key import -n "$KEY_NAME" --yes "$id" "$secret" >/dev/null
    set_env S3_ACCESS_KEY_ID "$id"
    set_env S3_SECRET_ACCESS_KEY "$secret"
    echo "Created key $KEY_NAME and wrote it to apps/api/.env"
  fi
  g bucket allow --read --write --owner "$BUCKET" --key "$KEY_NAME" >/dev/null

  # Garage's CLI has no CORS command; use the S3 API with the key just configured.
  (cd "$ROOT/apps/api" && APP_ORIGIN="$APP_ORIGIN" pnpm exec tsx --env-file=.env scripts/set-bucket-cors.ts)
  echo "Done. Restart the API (pnpm dev:api) so it picks up the new keys."
}

s3_up() { nc -z 127.0.0.1 3900 2>/dev/null; }

initialized() {
  grep -qE "^S3_ACCESS_KEY_ID=GK" "$API_ENV" 2>/dev/null &&
    g bucket info "$BUCKET" >/dev/null 2>&1 && g key info "$KEY_NAME" >/dev/null 2>&1
}

case "${1:-}" in
  start) write_config; exec garage -c "$CONFIG" server ;;
  serve)
    if s3_up; then
      echo "Garage is already running on 127.0.0.1:3900; using it."
      while sleep 86400; do :; done # stay alive so the other services keep running
    fi
    write_config
    echo "Starting Garage on 127.0.0.1:3900 (data in .garage-dev/, warnings only; RUST_LOG=info for more)"
    RUST_LOG="${RUST_LOG:-warn}" exec garage -c "$CONFIG" server
    ;;
  wait)
    for _ in $(seq 1 60); do s3_up && exit 0; sleep 0.5; done
    echo "Garage did not start on 127.0.0.1:3900 within 30 s." >&2
    exit 1
    ;;
  init)
    if [[ "${2:-}" == "--if-needed" ]] && initialized; then exit 0; fi
    init
    ;;
  *) echo "usage: $0 start|init|serve|wait" >&2; exit 1 ;;
esac
